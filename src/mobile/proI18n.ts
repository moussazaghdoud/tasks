const DICTIONARIES: Partial<Record<Lang, Record<ProKey, string>>> = { en: EN, fr: FR, it: IT, es: ES, de: DE, zh: ZH };

export function pt(key: ProKey, vars?: Record<string, string | number>): string {
  const text = (DICTIONARIES[currentLang()] ?? EN)[key];
  return vars ? text.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? '')) : text;
}
